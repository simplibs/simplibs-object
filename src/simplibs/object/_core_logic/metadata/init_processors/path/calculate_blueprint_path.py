from typing import TYPE_CHECKING
# Outers
from ...constants import BASE_CLASS_NAMES
# Annotations
if TYPE_CHECKING:
    from .....protocols.classes import SimpleClassLike


def calculate_blueprint_path(
    cls: "SimpleClassLike"
) -> str:
    """
    Helper function that traverses the MRO to construct a string representation: MyClass(Parent1, Parent2).
    It completely ignores core framework root classes such as SimpleObject, SimpleBase, etc.
    """

    # 1. Internal import of the root base class
    from .....SimpleBase import SimpleBase

    # 2. Inspect ancestors
    # Extract all ancestor classes from the MRO that inherit from SimpleBase,
    # excluding the core framework roots defined in BASE_CLASS_NAMES and the class itself.
    parents = [
        mro_class.__name__ for mro_class in cls.__mro__
        if issubclass(mro_class, SimpleBase) and
           mro_class.__name__ not in BASE_CLASS_NAMES and
           mro_class != cls
    ]

    # 3. Construct and return the structural path string
    return (
        cls.__name__
        if not parents else
        f"{cls.__name__}({', '.join(parents)})"
    )


