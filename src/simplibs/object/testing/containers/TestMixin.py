from simplibs.sentinels import UNSET
# Outers
from ...mixins.base_class import SimpleMixin


class TestMixin(SimpleMixin):
    """Universal test mixin used for shallow and deep validation of SimpleObject instances.

    Serves as a synthetic test double attached during dynamic class composition tests.
    It validates that the mixin injection pipeline correctly processes:
        - Slot attribute definition and initialization (``_test_slot``)
        - Property propagation and setter/getter hooks (``test_property``)
        - Instance method propagation (``test_method``)
        - Instance initialization hooks (``init_mixins``)
        - Dynamic class structure extension hooks (``__extend_instance_class__``)
    """

    # ------------------------------------------------------------
    # Compatibility Flags (Unrestricted for test flexibility)
    # ------------------------------------------------------------
    _constant_only = False
    _composite_only = False
    _mutable_only = False
    _immutable_only = False
    _only_types = UNSET

    # ------------------------------------------------------------
    # Slot Definition
    # ------------------------------------------------------------
    __slots__ = ("_test_slot",)

    # ------------------------------------------------------------
    # Initialization Hook
    # ------------------------------------------------------------
    def init_mixins(self) -> None:
        """Executes during instance initialization.

        Sets the test slot attribute to a deterministic default value to enable
        downstream slot presence and initialization assertions.
        """
        super().init_mixins()
        self._test_slot = "test_value"

    # ------------------------------------------------------------
    # Property Exposing the Slot State
    # ------------------------------------------------------------
    @property
    def test_property(self) -> str:
        """Returns the internal test slot state value."""
        return self._test_slot

    @test_property.setter
    def test_property(self, value: str) -> None:
        """Sets the internal test slot state value."""
        self._test_slot = value

    # ------------------------------------------------------------
    # Instance Method for Propagation Testing
    # ------------------------------------------------------------
    def test_method(self) -> str:
        """Simple instance method returning a formatted state string."""
        return f"[TestMixin] property={self._test_slot}"

    # ------------------------------------------------------------
    # Dynamic Class Extension Hook
    # ------------------------------------------------------------
    @staticmethod
    def __extend_instance_class__(instance_cls: type) -> type:
        """Injects class-level attributes and methods into the generated instance class.

        Verifies that mixins can successfully intercept and modify the dynamically created
        runtime class prior to object instantiation.

        Args:
            instance_cls: The dynamic subclass generated by the instance builder.

        Returns:
            The modified runtime class blueprint.
        """
        # 1. Inject class-level attribute
        setattr(instance_cls, "test_class_attribute", "class_level_ok")

        # 2. Inject class-level method
        def test_class_method(self) -> str:
            return "class_method_ok"

        setattr(instance_cls, "test_class_method", test_class_method)

        return instance_cls


