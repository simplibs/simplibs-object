class DirMixin:
    __slots__ = ()
    def __dir__(self):
        # Standardní atributy + jména inners pokud existují
        base = list(object.__dir__(self))
        if hasattr(self, "meta") and self.meta.inners:
            base += [inner.name_snake for inner in self.meta.inners]
        return sorted(set(base))

